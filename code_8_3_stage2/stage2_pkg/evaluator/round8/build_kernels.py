def _node_names(node):
    if isinstance(node, (ast.FunctionDef, ast.ClassDef)): return [node.name]
    if isinstance(node, ast.Assign):
        out = []
        for tg in node.targets:
            if isinstance(tg, ast.Name): out.append(tg.id)
            elif isinstance(tg, ast.Tuple): out += [e.id for e in tg.elts if isinstance(e, ast.Name)]
        return out
    return []

def extract(key, name):
    """(first line, last line, text) of the top-level statement defining `name` in source `key`: full physical lines,
    decorators included; for a line holding several statements (a; b; c) the whole line."""
    path = SRC[key]; text = open(path).read(); lines = text.split('\n'); tree = ast.parse(text)
    hits = [n for n in tree.body if name in _node_names(n)]
    assert len(hits) == 1, (key, name, len(hits))
    n = hits[0]
    lo = min([n.lineno]+[d.lineno for d in getattr(n, 'decorator_list', [])]); hi = n.end_lineno
    return lo, hi, '\n'.join(lines[lo-1:hi])+'\n'

def sha(txt): return hashlib.sha256(txt.encode()).hexdigest()

def build():
    manifest = dict(note=GEN_NOTE, sources={k: os.path.relpath(v, HERE) for k, v in SRC.items()},
                    source_sha256={k: hashlib.sha256(open(v, 'rb').read()).hexdigest() for k, v in SRC.items()}, modules={})
    for mod, plan in PLAN.items():
        out = [HEADERS[mod].format(note=GEN_NOTE), '# ======== verbatim blocks below ========\n']
        blocks = []; seen = set()
        for key, names in plan:
            for nm in names:
                lo, hi, txt = extract(key, nm)
                if (key, lo, hi) in seen: continue
                seen.add((key, lo, hi))
                h = sha(txt)
                out.append(f"\n# --- verbatim {os.path.relpath(SRC[key], HERE)} lines {lo}-{hi} sha256 {h}\n")
                out.append(txt)
                blocks.append(dict(source=key, name=nm, lines=[lo, hi], sha256=h))
        path = os.path.join(HERE, mod+'.py')
        open(path, 'w').write(''.join(out))
        manifest['modules'][mod] = dict(file=mod+'.py', blocks=blocks, sha256=hashlib.sha256(open(path, 'rb').read()).hexdigest())
        print(f"{mod}.py: {len(blocks)} verbatim blocks")
    json.dump(manifest, open(os.path.join(HERE, 'kernels_manifest.json'), 'w'), indent=1)
    return manifest


if __name__ == '__main__':
    build()
