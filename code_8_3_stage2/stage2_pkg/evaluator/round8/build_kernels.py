"""Round 8, Part A2 support: verbatim extraction of the reused numerical code into theta_0-free modules.

Why: the design module may import nothing that holds theta_0 (spec §1.3). The frozen modules it must reuse --
density_recursion_v1.py (the accepted evaluator), evaluator_fast.py (window path), round4/evaluator_window.py (general window
path), round4/trigger_dp.py (the DP) -- all execute the mc83.py / mc85_scan.py setup block at import time, which builds the
true frequency response Gj and the nominal output x (i.e. holds theta_0). They cannot be imported by the design module.

What: this script copies the needed top-level functions, classes and constant assignments VERBATIM (exact source lines,
decorators included, located with the ast module) into four generated modules that mirror the originals' structure:

  r8k_dr.py  <- mc83.py (phi, cfun), mc85_scan.py (regressors), density_recursion_v1.py (WB, make_grid, run_v0, _kernel,
                _prefix, _window, _ab_step, run_ab, _warmup, evaluate)
  r8k_ef.py  <- evaluator_fast.py (s/D/K, RHO/DISP/MARGIN, R, windows, _ab_step_w, full_step, AssertionStop, run_window,
                evaluate_fast, _warmup)
  r8k_ew.py  <- round4/evaluator_window.py (constants, AssertionStop, windows88, _tails, _gen_step, _gen_back, _warmup,
                ConstTable, StepTable, CodeTable, code_to_m, SOD_CODE, _buffers, forward, backward, design_grid,
                run_general, evaluate_table)
  r8k_td.py  <- round4/trigger_dp.py (constants, _value_ext, _dp_step, _warmup, Design)

Each generated module has a short NEW header (imports; constants taken from declared.py; in r8k_dr the replacement of
density_recursion_v1.input_arrays by a registry of (x_hat, H) set by the design module) followed by the verbatim blocks, each
preceded by a provenance comment (source file, line range, sha256 of the block text). The manifest kernels_manifest.json
lists every block; checks_r8.py re-extracts every block from the frozen sources and requires byte equality, checks that every
global name a block uses is defined, and checks that the generated modules import nothing that holds theta_0.

Usage (from this directory): python3 build_kernels.py      -> r8k_dr.py, r8k_ef.py, r8k_ew.py, r8k_td.py, kernels_manifest.json
"""
